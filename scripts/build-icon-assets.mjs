import fs from 'node:fs/promises';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const webRequire = createRequire(path.join(root, 'apps/web/package.json'));
const sharp = createRequire(webRequire.resolve('next/package.json'))('sharp');
const source = await fs.readFile(path.join(root, 'packages/design-tokens/src/icons.ts'), 'utf8');
const js = ts.transpileModule(source, {
  compilerOptions: { module: ts.ModuleKind.ESNext },
}).outputText;
const { iconPaths } = await import(
  `data:text/javascript;base64,${Buffer.from(js).toString('base64')}`
);
const directory = path.join(root, 'packages/ui-mobile/assets/icons');
await fs.mkdir(directory, { recursive: true });
const imports = [];
const entries = [];
for (const [name, paths] of Object.entries(iconPaths)) {
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="#000" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round">${paths.map((d) => `<path d="${d}"/>`).join('')}</svg>`;
  await sharp(Buffer.from(svg))
    .resize(96, 96)
    .png()
    .toFile(path.join(directory, `${name}.png`));
  const identifier = `icon${imports.length}`;
  imports.push(`import ${identifier} from '../assets/icons/${name}.png';`);
  entries.push(`  '${name}': ${identifier},`);
}
await fs.writeFile(
  path.join(root, 'packages/ui-mobile/src/iconImages.ts'),
  `// Generated by scripts/build-icon-assets.mjs. Edit shared icon paths instead.\nimport type { IconName } from '@daynori/design-tokens';\nimport type { ImageSourcePropType } from 'react-native';\n${imports.join('\n')}\n\nexport const iconImages: Record<IconName, ImageSourcePropType> = {\n${entries.join('\n')}\n};\n`
);
console.log(`Generated ${entries.length} native icons from shared vector paths.`);
